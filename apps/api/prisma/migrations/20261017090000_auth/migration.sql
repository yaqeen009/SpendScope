-- Authentication and workspace ownership.
--
-- Introduces `User` (accounts) and `Session` (opaque server-side sessions) and
-- links each `Workspace` to an owning user. `ownerUserId` is nullable so the
-- migration is non-destructive: workspaces created before authentication stay
-- in the database but are not reachable through the API until they are claimed
-- by a first registration (see the workspace service).

